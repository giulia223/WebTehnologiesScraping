"""docs/METRICS.md: the metrics as a readable, self-contained report."""

from typing import Any

from techdetect.evaluate.metrics import CONFIDENCE_BANDS, GROUP_ORDER, MIN_N, rate, rate_if_enough

GROUP_MEANING = {
    "core": "used to build the website: seen working or stated by the website itself, or "
    "implied by such a detection (tier inferred); themes, plugins and apps included (the "
    "headline count)",
    "dns_only": "found only in DNS records (mail provider, verification tokens)",
}


def render(m: dict[str, Any]) -> str:
    parts = [
        _intro(m),
        _headline(m),
        _breakdowns(m),
        _false_positives(m),
        _unsure(m),
        _missed(m),
    ]
    return "\n\n".join(p for p in parts if p) + "\n"


def _intro(m: dict[str, Any]) -> str:
    sets = m["labelled_domains"]
    lines = [
        "# Metrics",
        "",
        "Generated by `techdetect evaluate metrics` from `data/ground_truth.json` and the "
        "current `data/output/detections.jsonl`. Do not edit by hand.",
        "",
        f"- **Labelled domains:** {len(sets['blind'])} blind (every 20th input row, picked by "
        f"position before the tool existed) and {len(sets['review'])} review (drawn at random "
        "with a fixed seed among the domains the tool could read).",
        f"- **Precision** uses the verdict on every counted detection of these domains "
        f"({m['judged']} detections{_below(m)}). Each was judged correct / wrong / unsure "
        "from its evidence and the saved raw data, by reviewers separate from the tool's "
        "author, following `docs/DEFINITIONS.md` (what counts as a technology the site "
        "uses). Unsure detections are left out of the percentage and counted apart.",
        "- **Recall** uses the blind domains only: an independent inspection listed every "
        "technology it could confirm before seeing any output of the tool. Recall is the share "
        "of that list the tool reports, in any group. It is measured against what that "
        "inspection found, so technologies it missed are missing here too: the real recall is "
        "likely lower. Part of it is also fitted to this set: on 2026-11-22, 9 rules were "
        "written from misses on these same blind domains. Before them recall was 66% (75/113), "
        "the last independent figure; the rules' real test is a fresh set of domains.",
        "- **F1** is the harmonic mean of the two.",
        f"- Every rate carries its counts. With fewer than {MIN_N} judged detections a "
        'breakdown says "too few to measure".',
    ]
    if m["platform_infra"]:
        agreed = sum(1 for x in m["platform_infra"] if x["verdict"] == "wrong")
        lines += [
            f"- **Left out of precision:** {len(m['platform_infra'])} detections the tool "
            "reports apart as a hosted platform's infrastructure (servers, CDN, certificate, "
            "bot protection, the platform's own tracking: not the site's choice). "
            f'{agreed} of them are labelled "not the site\'s" (wrong as a claim about the '
            "site), so moving them apart agrees with the labels there.",
        ]
    if m["unlabelled"] or m["stale"]:
        lines += [
            "",
            f"**Warning:** {len(m['unlabelled'])} detections have no verdict and "
            f"{len(m['stale'])} verdicts belong to detections no longer reported: the labels "
            "predate the current detection run and need updating.",
        ]
    return "\n".join(lines)


def _below(m: dict[str, Any]) -> str:
    k = m.get("judged_below_threshold", 0)
    verb = "is" if k == 1 else "are"
    return f"; {k} more, below the default confidence threshold, {verb} not counted" if k else ""


def _headline(m: dict[str, Any]) -> str:
    rows = [
        "## Headline",
        "",
        "A threshold keeps only detections whose confidence (the rule author's estimate, "
        f"0-100) is at least that value. The default ({m['default_threshold']}, marked) is "
        "the one `techdetect detect` counts with: a detection whose clues are all worth 0 "
        "is not counted.",
        "",
        "| Threshold | Precision | Precision, blind set | Precision, review set | Unsure "
        "| Recall | Recall where a rule exists | F1 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for h in m["headline"]:
        f1 = f"{h['f1']:.2f}" if h["f1"] is not None else "n/a"
        threshold = f"{h['threshold']} (default)" if h["default"] else str(h["threshold"])
        rows.append(
            f"| {threshold} | {rate(*h['precision'])} | {rate(*h['precision_blind'])} "
            f"| {rate(*h['precision_review'])} | {h['unsure']} | {rate(*h['recall'])} "
            f"| {rate(*h['recall_with_rule'])} | {f1} |"
        )
    rows += [
        "",
        '"Recall where a rule exists" counts only the technologies the rule set knows: a miss '
        "there is a rule or collection failure; the rest are technologies no rule could catch.",
    ]
    return "\n".join(rows)


def _table(title: str, tallies: dict[str, dict[str, int]], order: list[str], note: str = "") -> str:
    rows = [f"### {title}", ""]
    if note:
        rows += [note, ""]
    rows += ["| | Precision | Wrong | Unsure |", "|---|---|---|---|"]
    for key in order:
        t = tallies.get(key, {"correct": 0, "wrong": 0, "unsure": 0})
        judged = t["correct"] + t["wrong"]
        precision = rate_if_enough(t["correct"], judged)
        rows.append(f"| {key} | {precision} | {t['wrong']} | {t['unsure']} |")
    return "\n".join(rows)


def _breakdowns(m: dict[str, Any]) -> str:
    groups = _table(
        "By group",
        m["by_group"],
        [g for g in GROUP_ORDER if g in m["by_group"]],
        "; ".join(f"**{g}**: {GROUP_MEANING[g]}" for g in GROUP_ORDER) + ".",
    )
    tiers = _table(
        "By evidence tier",
        m["by_tier"],
        sorted(m["by_tier"]),
        "**observed**: seen working (a script, request, header, cookie, global); "
        "**declared**: the site states it (generator tag, DNS verification token); "
        "**inferred**: only implied by another technology.",
    )
    bands = _table(
        "By confidence",
        m["by_confidence"],
        [name for name, _, _ in CONFIDENCE_BANDS],
        "Measured precision for each confidence level, to decide whether a higher threshold "
        "would help.",
    )
    big = [c for c, t in m["by_category"].items() if t["correct"] + t["wrong"] >= MIN_N]
    small = len(m["by_category"]) - len(big)
    categories = _table(
        "By category",
        m["by_category"],
        sorted(big, key=lambda c: -(m["by_category"][c]["correct"] + m["by_category"][c]["wrong"])),
        f"Only categories with at least {MIN_N} judged detections; {small} other categories "
        "have too few to measure. A technology with several categories counts in each.",
    )
    title = f"## Precision breakdowns (default threshold, {m['default_threshold']})"
    return "\n\n".join([title, groups, tiers, bands, categories])


def _evidence_line(d: dict[str, Any]) -> str:
    if d["implied_by"]:
        return f"implied by {d['implied_by']}, no evidence of its own"
    pattern = d["pattern"] or "(present)"
    return (
        f"{d['signal']}, rule `{_code(pattern)}` matched `{_code(d['matched'])}` "
        f"in {d['artifact']} at {_code(d['location'])}"
    )


def _code(text: str, limit: int = 90) -> str:
    text = str(text).replace("`", "'").replace("|", "\\|").replace("\n", " ")
    return text if len(text) <= limit else text[: limit - 3] + "..."


def _detection_rows(items: list[dict[str, Any]]) -> list[str]:
    rows = ["| Domain | Technology | Conf. | Group | Why | Evidence |", "|---|---|---|---|---|---|"]
    for d in sorted(items, key=lambda d: (d["domain"], d["technology"])):
        rows.append(
            f"| {d['domain']} | {d['technology']} | {d['confidence']} | {d['group']} "
            f"| {_code(d['reason'], 300)} | {_evidence_line(d)} |"
        )
    return rows


def _false_positives(m: dict[str, Any]) -> str:
    return "\n".join(
        [
            f"## Every false positive ({len(m['false_positives'])})",
            "",
            "Detections judged wrong, with the reviewer's reason and the first piece of "
            "evidence the tool gave.",
            "",
            *_detection_rows(m["false_positives"]),
        ]
    )


def _unsure(m: dict[str, Any]) -> str:
    return "\n".join([f"## Unsure ({len(m['unsure'])})", "", *_detection_rows(m["unsure"])])


def _missed(m: dict[str, Any]) -> str:
    rows = [
        f"## Missed on the blind domains ({len(m['missed'])})",
        "",
        'Technologies the blind inspection found that the tool does not report. "No rule" '
        "means the rule set has no technology by that name.",
        "",
        "| Domain | Technology | Rule exists | Where the inspection saw it |",
        "|---|---|---|---|",
    ]
    for e in sorted(m["missed"], key=lambda e: (e["domain"], not e["in_rules"], e["technology"])):
        rule = "yes" if e["in_rules"] else "no rule"
        rows.append(f"| {e['domain']} | {e['technology']} | {rule} | {_code(e['where'], 140)} |")
    if m["not_counted"]:
        rows += [
            "",
            f"Not counted for recall ({len(m['not_counted'])}): items of the blind lists that "
            "are not the site's own under `docs/DEFINITIONS.md` (a hosted platform's "
            "infrastructure): "
            + ", ".join(f"{n['technology']} ({n['domain']})" for n in m["not_counted"])
            + ".",
        ]
    return "\n".join(rows)
